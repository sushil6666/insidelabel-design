"""
D-148: the Play app is a Trusted Web Activity of https://insidelabel.ai/app/
(D-010), generated by Bubblewrap into android/. These checks hold the values
that can't drift: the package (D-149, permanent after the first upload), the
host (D-114), the scope, Play's target API level, no notifications and no
permissions, and above all that no signing key is ever in the repo (D-012:
the upload key stays on Sushil's laptop).
"""
import hashlib
import json
import os
import re
import subprocess

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ANDROID = os.path.join(ROOT, "android")
PACKAGE = "ai.insidelabel.app.f"
# Play's target API level requirement, read 2026-10-01 from
# https://developer.android.com/google/play/requirements/target-sdk (last updated
# 2026-09-16): "Starting August 31 2026: New apps and app updates must target
# Android 16 (API level 36) or higher to be submitted to Google Play".
PLAY_TARGET_SDK = 36
KEY_FILE = re.compile(r"\.(jks|keystore|p12|pfx|pk8)$|(^|/)keystore\.properties$", re.I)


def _read(*parts):
    with open(os.path.join(ANDROID, *parts), encoding="utf-8") as fh:
        return fh.read()


def _git(*args):
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, check=False)
    except OSError:
        pytest.skip("git not available")


def test_no_signing_key_is_tracked():
    out = _git("ls-files", "-z")
    if out.returncode != 0:
        pytest.skip("not a git checkout")
    keys = [p for p in out.stdout.decode().split("\0") if p and KEY_FILE.search(p)]
    assert not keys, "a signing key is tracked; remove it from git and rotate it: " + ", ".join(keys)


@pytest.mark.parametrize("path", ["insidelabel-upload.jks", "android/android.keystore",
                                  "android/app/upload.p12", "android/keystore.properties",
                                  "android/app-release-bundle.aab", "android/app/build/x.apk"])
def test_keys_and_build_output_are_ignored(path):
    out = _git("check-ignore", "-q", "--no-index", path)
    if out.returncode == 128:
        pytest.skip("not a git checkout")
    assert out.returncode == 0, f"{path} is not git-ignored"


def test_twa_manifest_holds_the_fixed_facts():
    m = json.loads(_read("twa-manifest.json"))
    web = json.load(open(os.path.join(ROOT, "web", "manifest.webmanifest"), encoding="utf-8"))
    assert m["packageId"] == PACKAGE
    assert m["host"] == "insidelabel.ai"                       # D-114: the only host
    assert m["startUrl"] == web["start_url"] == "/app/"
    assert m["fullScopeUrl"] == "https://insidelabel.ai" + web["scope"]
    assert m["webManifestUrl"] == "https://insidelabel.ai/app/manifest.webmanifest"
    assert m["name"] == m["launcherName"] == web["name"] == "InsideLabel"
    assert m["themeColor"].lower() == web["theme_color"].lower()
    assert m["backgroundColor"].lower() == web["background_color"].lower()
    assert m["iconUrl"] == "https://insidelabel.ai/app/icon-512.png"
    assert m["maskableIconUrl"] == "https://insidelabel.ai/app/icon-maskable-512.png"
    assert m["orientation"] == web["orientation"] == "portrait"
    assert isinstance(m["appVersionCode"], int) and m["appVersionCode"] >= 1
    assert m["enableNotifications"] is False                   # no notifications (D-148)
    assert m["features"] == {}                                 # no location, no Play Billing
    assert m["fallbackType"] == "customtabs"
    assert "127.0.0.1" not in json.dumps(m) and "localhost" not in json.dumps(m)


def test_signing_key_path_points_outside_the_repo():
    m = json.loads(_read("twa-manifest.json"))
    key = os.path.normpath(os.path.join(ANDROID, m["signingKey"]["path"]))
    assert not key.startswith(ROOT + os.sep), key


def test_gradle_build_matches_the_manifest_and_play():
    gradle = _read("app", "build.gradle")
    assert f'applicationId "{PACKAGE}"' in gradle
    assert f'namespace "{PACKAGE}"' in gradle
    assert f"targetSdkVersion {PLAY_TARGET_SDK}" in gradle
    assert f"compileSdkVersion {PLAY_TARGET_SDK}" in gradle
    m = json.loads(_read("twa-manifest.json"))
    assert f"versionCode {m['appVersionCode']}\n" in gradle
    assert "hostName: 'insidelabel.ai'" in gradle
    assert "launchUrl: '/app/'" in gradle
    assert "enableNotifications: false" in gradle
    assert "'https://insidelabel.ai/app/manifest.webmanifest'" in gradle
    assert "127.0.0.1" not in gradle and "localhost" not in gradle
    assert "billing" not in gradle.lower() and "location" not in gradle.lower()


def test_android_manifest_asks_for_no_permission():
    # Camera access inside a Trusted Web Activity is Chrome's own permission
    # prompt for the site; the app itself asks for nothing.
    manifest = _read("app", "src", "main", "AndroidManifest.xml")
    assert "<uses-permission" not in manifest
    assert f'package="{PACKAGE}"' in manifest
    assert 'android:pathPrefix="/app/"' in manifest
    statements = _read("app", "src", "main", "res", "values", "strings.xml")
    assert '\\"site\\": \\"https://insidelabel.ai\\"' in statements


def test_the_project_was_generated_from_the_committed_twa_manifest():
    # `bubblewrap build` compares this checksum with twa-manifest.json and offers
    # to regenerate the project when they differ. Edit twa-manifest.json, then run
    # `bubblewrap update --skipVersionUpgrade` in android/ and commit what it writes.
    with open(os.path.join(ANDROID, "twa-manifest.json"), "rb") as fh:
        current = hashlib.sha1(fh.read()).hexdigest()
    assert _read("manifest-checksum.txt").strip() == current
